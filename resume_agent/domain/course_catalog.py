# 类别展示顺序（综合类学校先工科经管，其次文理医艺等）
CATEGORY_ORDER = ["工科", "理科", "经管", "文法", "医学", "教育", "农林", "艺术"]


def catalog_majors():
    return list(MAJOR_CATEGORIES.keys())


def courses_for_major(major):
    return list(MAJOR_COURSES.get(major.strip(), []))


def school_category(school_name: str) -> str:
    """根据学校名称推断学校类型；未知则视为综合类。"""
    name = (school_name or "").strip()
    if not name:
        return "综合"
    rules = [
        ("师范", "教育"),
        ("财经", "经管"),
        ("经济", "经管"),
        ("工商", "经管"),
        ("商业", "经管"),
        ("医科", "医学"),
        ("医学", "医学"),
        ("中医药", "医学"),
        ("药学", "医学"),
        ("政法", "文法"),
        ("语言", "文法"),
        ("外国语", "文法"),
        ("农业", "农林"),
        ("林业", "农林"),
        ("农林", "农林"),
        ("艺术", "艺术"),
        ("美术", "艺术"),
        ("音乐", "艺术"),
        ("戏剧", "艺术"),
        ("体育", "艺术"),
    ]
    for keyword, category in rules:
        if keyword in name:
            return category
    if any(
        keyword in name
        for keyword in ("理工", "工业", "科技", "电子", "邮电", "航空",
                        "航天", "交通", "石油", "矿业", "地质", "电力",
                        "建筑", "海洋", "工程", "信息")
    ):
        return "工科"
    return "综合"


def majors_for_school(school_name: str):
    """按学校类型排序的专业选项：本校特色类别优先，其余类别按通用顺序。"""
    category = school_category(school_name)
    if category == "综合":
        ordered = CATEGORY_ORDER
    else:
        ordered = [category] + [item for item in CATEGORY_ORDER if item != category]
    majors = catalog_majors()
    ranked = []
    for item in ordered:
        ranked.extend(
            major for major in majors if MAJOR_CATEGORIES[major] == item
        )
    return ranked
